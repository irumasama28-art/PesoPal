using System.Text;
using CashLedgerAndroid.Models;
using SQLite;

namespace CashLedgerAndroid.Services;

public class LedgerDatabase
{
    private SQLiteAsyncConnection _db;
    private readonly SemaphoreSlim _gate = new SemaphoreSlim(1, 1);
    private bool _initialized;
    private Exception? _initException;

    public static string DatabasePath => Path.Combine(FileSystem.AppDataDirectory, "cashledger.db3");

    // Raised after any change so open screens can refresh themselves.
    public event Action? DataChanged;

    public LedgerDatabase()
    {
        try
        {
            _db = new SQLiteAsyncConnection(DatabasePath);
        }
        catch (Exception ex)
        {
            // Capture initialization error; actual initialization will be attempted later
            _db = null!;
            _initException = ex;
        }
    }

    public Exception? InitializationException => _initException;

    public async Task InitializeAsync()
    {
        if (_initialized) return;
        await _gate.WaitAsync();
        try
        {
            if (_initialized) return;
            try
            {
                if (_db == null)
                    _db = new SQLiteAsyncConnection(DatabasePath);

                await _db.CreateTableAsync<TransactionRecord>();
                await _db.CreateTableAsync<AppSettings>();
                await _db.CreateTableAsync<RecurringTransaction>();
                var existing = await _db.Table<AppSettings>().Where(s => s.Id == 1).FirstOrDefaultAsync();
                if (existing is null) await _db.InsertAsync(new AppSettings());
                _initialized = true;
                _initException = null;
            }
            catch (Exception ex)
            {
                // Store the exception so callers can surface a friendly error instead of letting the app crash.
                _initException = ex;
                throw;
            }
        }
        finally
        {
            _gate.Release();
        }
    }

    private void Changed() => DataChanged?.Invoke();

    public async Task<List<TransactionRecord>> GetTransactionsAsync()
    {
        await InitializeAsync();
        return await _db.Table<TransactionRecord>().OrderByDescending(t => t.CreatedAt).ToListAsync();
    }

    // After the insert, record.Id holds the new ID generated by SQLite.
    public async Task<int> SaveTransactionAsync(TransactionRecord record)
    {
        await InitializeAsync();
        var rows = await _db.InsertAsync(record);
        Changed();
        return rows;
    }

    public async Task<int> UpdateTransactionAsync(TransactionRecord record)
    {
        await InitializeAsync();
        var rows = await _db.UpdateAsync(record);
        Changed();
        return rows;
    }

    public async Task<int> DeleteTransactionAsync(TransactionRecord record)
    {
        await InitializeAsync();
        var rows = await _db.DeleteAsync(record);
        Changed();
        return rows;
    }

    public async Task<AppSettings> GetSettingsAsync()
    {
        await InitializeAsync();
        return await _db.Table<AppSettings>().Where(s => s.Id == 1).FirstAsync();
    }

    public async Task<int> SaveSettingsAsync(AppSettings settings)
    {
        await InitializeAsync();
        var rows = await _db.UpdateAsync(settings);
        Changed();
        return rows;
    }

    // ---- Backup and restore ----

    public static string LastBackupText()
    {
        var raw = Preferences.Default.Get("last_backup", "");
        if (DateTime.TryParse(raw, null, System.Globalization.DateTimeStyles.RoundtripKind, out var when))
            return when.ToString("MMM d, yyyy h:mm tt", Fmt.Inv);
        return "";
    }

    public async Task<string> CreateBackupFileAsync()
    {
        await InitializeAsync();
        var name = "cash-ledger-backup-" + DateTime.Now.ToString("yyyyMMdd-HHmmss", Fmt.Inv) + ".db3";
        var path = Path.Combine(FileSystem.CacheDirectory, name);
        File.Copy(DatabasePath, path, true);
        Preferences.Default.Set("last_backup", DateTime.Now.ToString("o", Fmt.Inv));
        return path;
    }

    public async Task RestoreFromAsync(string sourcePath)
    {
        // A valid SQLite file always starts with "SQLite format 3".
        using (var fs = File.OpenRead(sourcePath))
        {
            var buffer = new byte[16];
            var read = fs.Read(buffer, 0, buffer.Length);
            var header = Encoding.ASCII.GetString(buffer, 0, read);
            if (!header.StartsWith("SQLite format 3", StringComparison.Ordinal))
                throw new InvalidDataException("This file is not a Cash Ledger backup.");
        }

        await _gate.WaitAsync();
        try
        {
            await _db.CloseAsync();
            File.Copy(sourcePath, DatabasePath, true);
            _db = new SQLiteAsyncConnection(DatabasePath);
            _initialized = false;
        }
        finally
        {
            _gate.Release();
        }

        await InitializeAsync();
        Changed();
    }

    // ===== Recurring Transaction Methods =====

    public async Task<List<RecurringTransaction>> GetRecurringTransactionsAsync()
    {
        await _gate.WaitAsync();
        try
        {
            return await _db.Table<RecurringTransaction>().ToListAsync();
        }
        finally { _gate.Release(); }
    }

    public async Task<RecurringTransaction?> GetRecurringTransactionAsync(int id)
    {
        await _gate.WaitAsync();
        try
        {
            return await _db.FindAsync<RecurringTransaction>(id);
        }
        finally { _gate.Release(); }
    }

    public async Task<int> SaveRecurringTransactionAsync(RecurringTransaction recurring)
    {
        await _gate.WaitAsync();
        try
        {
            var result = await _db.InsertAsync(recurring);
            Changed();
            return result;
        }
        finally { _gate.Release(); }
    }

    public async Task<int> UpdateRecurringTransactionAsync(RecurringTransaction recurring)
    {
        await _gate.WaitAsync();
        try
        {
            var result = await _db.UpdateAsync(recurring);
            Changed();
            return result;
        }
        finally { _gate.Release(); }
    }

    public async Task<int> DeleteRecurringTransactionAsync(RecurringTransaction recurring)
    {
        await _gate.WaitAsync();
        try
        {
            var result = await _db.DeleteAsync(recurring);
            Changed();
            return result;
        }
        finally { _gate.Release(); }
    }

    /// <summary>
    /// Process due recurring transactions and generate TransactionRecords
    /// </summary>
    public async Task<int> ProcessDueRecurringTransactionsAsync()
    {
        await _gate.WaitAsync();
        try
        {
            int generatedCount = 0;
            var recurring = await _db.Table<RecurringTransaction>()
                .Where(r => r.IsActive)
                .ToListAsync();

            foreach (var recurring_item in recurring)
            {
                if (recurring_item.IsWithinActiveRange() && recurring_item.IsDue())
                {
                    // Generate a new transaction
                    var newTransaction = new TransactionRecord
                    {
                        CustomerName = recurring_item.CustomerName,
                        Type = recurring_item.Type,
                        Amount = recurring_item.Amount,
                        Fee = recurring_item.Fee,
                        ReferenceNumber = recurring_item.ReferenceNumber,
                        Notes = recurring_item.Notes,
                        CreatedAt = DateTime.Now
                    };

                    await _db.InsertAsync(newTransaction);
                    recurring_item.LastProcessedDate = DateTime.Now;
                    await _db.UpdateAsync(recurring_item);
                    generatedCount++;
                }
            }

            if (generatedCount > 0)
                Changed();

            return generatedCount;
        }
        finally { _gate.Release(); }
    }
}
